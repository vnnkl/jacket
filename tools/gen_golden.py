"""Write esp32/test/test_core/golden_shows.h: the Mac shows' exact packets, so the firmware must match byte for byte."""
import pathlib
from jacket.effects import disco_rainbow
from jacket.shows import big_show, small_pulse

SHOWS = {"small": small_pulse(60, 2.0), "medium": disco_rainbow(3.0), "big": big_show(10.0)}
OUT = pathlib.Path(__file__).resolve().parent.parent / "esp32/test/test_core/golden_shows.h"


def emit(name, steps):
    rows = ",\n".join(
        "    {{%s}, %d, %d}" % (", ".join(f"0x{b:02X}" for b in p), len(p), round(d * 1000)) for p, d in steps
    )
    return f"static const GoldenStep kGolden_{name}[] = {{\n{rows}\n}};\n"


def main():
    body = "".join(emit(n, s) for n, s in SHOWS.items())
    OUT.write_text(
        "// Generated by tools/gen_golden.py from the Mac implementation - do not edit.\n#pragma once\n"
        "#include <stdint.h>\n#include <stddef.h>\n"
        "struct GoldenStep { uint8_t data[16]; size_t len; uint32_t delayMs; };\n" + body
    )
    print(f"wrote {OUT} ({', '.join(f'{n}: {len(s)} steps' for n, s in SHOWS.items())})")


if __name__ == "__main__":
    main()
